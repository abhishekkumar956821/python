#list.insert(index, value) # This method inserts an element at a specified index in the list
list = [2, 1, 3, 4, 5, 6, 7, 8, 9, 10]
print("Original List:", list)
list.insert(0, 0) # Inserting 0 at the start of the list
print("List after inserting 0 at the start:", list)
list.insert(5, 11) # Inserting 11 at index 5
print("List after inserting 11 at index 5:", list)